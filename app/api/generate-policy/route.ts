import { NextResponse } from "next/server";
import { parsePolicyOutput } from "@/lib/parser";

export async function POST(req: Request) {
  try {
    const body = await req.json();
    const { prompt } = body;

    if (!prompt) {
      return NextResponse.json(
        { error: "Prompt is required" },
        { status: 400 }
      );
    }

    const apiKey = process.env.OPENAI_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        { error: "OpenAI API key not configured" },
        { status: 500 }
      );
    }

    const response = await fetch("https://api.openai.com/v1/chat/completions", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${apiKey}`,
      },
      body: JSON.stringify({
        model: "gpt-4",
        messages: [{ role: "user", content: prompt }],
        temperature: 0.2,
      }),
    });

    if (!response.ok) {
      const errorData = await response.json().catch(() => ({
        error: { message: "Unknown OpenAI API error" },
      }));
      return NextResponse.json(
        {
          error: `OpenAI API error: ${
            errorData.error?.message || `HTTP ${response.status}`
          }`,
        },
        { status: response.status }
      );
    }

    const data = await response.json();

    if (
      !data.choices ||
      !Array.isArray(data.choices) ||
      data.choices.length === 0
    ) {
      return NextResponse.json(
        { error: "Invalid response format from OpenAI API" },
        { status: 500 }
      );
    }

    const rawContent = data.choices[0]?.message?.content;
    if (!rawContent) {
      return NextResponse.json(
        { error: "No content generated by OpenAI API" },
        { status: 500 }
      );
    }

    // Parse structured output to extract POLICY-MARKDOWN and METAJSON
    const parsed = parsePolicyOutput(rawContent);

    return NextResponse.json({
      content: parsed.content,
      metadata: parsed.metadata,
      hasStructure: parsed.hasStructure,
    });
  } catch (e: any) {
    return NextResponse.json(
      { error: e.message ?? "Failed to generate policy" },
      { status: 500 }
    );
  }
}
